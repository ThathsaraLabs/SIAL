const switcher = document.querySelector('.language-switch');
const buttons = switcher.querySelectorAll('[data-language]');
const textEntries = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (switcher.contains(node) || node.parentElement.closest('[aria-hidden="true"]')) continue;
  const original = node.data;
  const key = original.trim();
  if (sinhala.has(key)) textEntries.push([node, original, original.replace(key, sinhala.get(key))]);
}

const attributes = [...document.querySelectorAll('[alt], [aria-label], meta[name="description"]')]
  .flatMap(element => ['alt', 'aria-label', 'content'].flatMap(name => {
    const original = element.getAttribute(name);
    return sinhala.has(original) ? [[element, name, original]] : [];
  }));
const englishTitle = document.title;
const localPageLinks = location.protocol === 'file:'
  ? [...document.querySelectorAll('a[href]')].filter(link =>
      link.protocol === 'file:' && link.pathname.endsWith('.html') &&
      link.pathname !== location.pathname)
  : [];


function applyLanguage(language) {
  const translate = language === 'si';
  document.documentElement.lang = language;
  localPageLinks.forEach(link => {
    const url = new URL(link.href);
    url.searchParams.set('lang', language);
    link.href = url.href;
  });
  document.title = translate ? sinhala.get(englishTitle) : englishTitle;
  textEntries.forEach(([node, english, translated]) => { node.data = translate ? translated : english; });
  attributes.forEach(([element, name, english]) => {
    element.setAttribute(name, translate ? sinhala.get(english) : english);
  });
  buttons.forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
}

let savedLanguage;
try { savedLanguage = localStorage.getItem('sial-home-language'); } catch {}
const linkedLanguage = new URLSearchParams(location.search).get('lang');
const initialLanguage = linkedLanguage === 'si' || linkedLanguage === 'en'
  ? linkedLanguage
  : savedLanguage;
applyLanguage(initialLanguage === 'si' ? 'si' : 'en');
switcher.hidden = false;
buttons.forEach(button => {
  button.addEventListener('click', () => {
    const language = button.dataset.language;
    applyLanguage(language);
    if (location.protocol === 'file:') {
      const url = new URL(location.href);
      url.searchParams.set('lang', language);
      try { history.replaceState(null, '', url); } catch {}
    }
    try { localStorage.setItem('sial-home-language', language); } catch {}
  });
});
